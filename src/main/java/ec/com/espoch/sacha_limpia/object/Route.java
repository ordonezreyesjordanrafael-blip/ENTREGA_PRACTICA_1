package ec.com.espoch.sacha_limpia.object;
public class Route {
    
 private String name;
 private int code;
 private int several;

    public Route() {
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public int getCode() {
        return code;
    }

    public void setCode(int code) {
        this.code = code;
    }

    public int getSeveral() {
        return several;
    }

    public void setSeveral(int several) {
        this.several = several;
    }
 
 
 
 
}
